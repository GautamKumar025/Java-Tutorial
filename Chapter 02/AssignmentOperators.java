public class AssignmentOperators {
    public static void main(String[] args){

        // Write your code here!

        System.out.println("Performe the Assignment Operators!");

        int a = 10;
        a += 5; // add 5 to a and assign the result to a!

        int b = 20;
        b -= 15; // subtraction of 15 from b and assign the result to b!

        int c = 30;
        c *= 5; // power the value of c by 5 and then assign to it c!
        
        int d = 40;
        d /= 8; // divisible the value of d by 8 and then assign to it d!

        int e = 50;
        e %= 10; // find the remainder when e is divisible by 10 and then assign to it e

        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
        System.out.println(d);
        System.out.println(e);
    }
    
}
